#!/usr/bin/env node
/**
 * Writes `src/theme-light.css`: the light theme as a mirror of Tailwind's palette (50↔950, 100↔900, … 500 stays).
 * The app is written dark-first with Tailwind colour utilities, which read `--color-<hue>-<shade>`; swapping the
 * scale turns dark panels light and light text dark without touching components.
 *
 * Run after upgrading Tailwind or using a new colour scale: `node scripts/gen-light-theme.mjs`
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const theme = readFileSync(join(root, 'node_modules/tailwindcss/theme.css'), 'utf8');

/** Colour scales the app uses (`grep -rhoE '(text|bg|border)-[a-z]+-[0-9]+' src`). */
const HUES = ['gray', 'red', 'orange', 'amber', 'yellow', 'green', 'cyan', 'sky', 'blue', 'violet', 'purple'];
const SHADES = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];
const MIRROR = { 50: 950, 100: 900, 200: 800, 300: 700, 400: 600, 500: 500, 600: 400, 700: 300, 800: 200, 900: 100, 950: 50 };

/**
 * Light-theme values that differ from the plain mirror. Secondary text (`gray-500`) must stay ≥4.5:1 on the light
 * page and panels; the dark theme's own `gray-500` lives in `index.css`.
 */
const OVERRIDES = { 'gray-500': '#5b6270' };

const value = (hue, shade) => {
  const m = new RegExp(`--color-${hue}-${shade}:\\s*([^;]+);`).exec(theme);
  if (!m) throw new Error(`--color-${hue}-${shade} not found in tailwindcss/theme.css`);
  return m[1].trim();
};

const decls = [];
for (const hue of HUES) {
  for (const shade of SHADES) {
    const key = `${hue}-${shade}`;
    decls.push(`  --color-${key}: ${OVERRIDES[key] ?? value(hue, MIRROR[shade])};`);
  }
}
const block = `${decls.join('\n')}\n  color-scheme: light;`;

const css = `/* Generated by scripts/gen-light-theme.mjs. Do not edit by hand. */

/* Light theme: the system setting (unless the user picked dark) or an explicit choice. */
@media (prefers-color-scheme: light) {
  :root:not([data-theme='dark']) {
${block.replace(/^/gm, '  ')}
  }
}

:root[data-theme='light'] {
${block}
}
`;

writeFileSync(join(root, 'src/theme-light.css'), css);
console.log(`Wrote src/theme-light.css (${HUES.length} scales)`);
